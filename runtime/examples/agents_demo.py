    print(f"  • Execution Result: {task_res1.result['status']}")
    print(f"  • Code Output Snippet: {task_res1.result['generated_code'].splitlines()[0]}")
    print(f"  • Execution Time: {task_res1.execution_time_ms:.2f} ms")

    task_res2 = coordinator.submit_task("security_scan", {"code": task_res1.result['generated_code']})
    print(f"✅ Security Audit Task Routed to: '{task_res2.assigned_agent_id}'")
    print(f"  • Security Score: {task_res2.result['security_score']}/100")
    print(f"  • Execution Time: {task_res2.execution_time_ms:.2f} ms")

    # Step 5: Circular Delegation Barrier Enforcement
