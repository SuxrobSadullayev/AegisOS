class CodeGeneratorAgent(AgentInterface):
    """Core agent responsible for Python code generation."""
    def __init__(self):
        self._descriptor = AgentDescriptor(
            agent_id="agent.core.code_generator",
            name="Aegis Core Code Generator Agent",
            version="1.0.0",
            capabilities=["PYTHON_GEN", "REFACTORING"],
            permissions=[PluginPermission.FILESYSTEM_READ, PluginPermission.FILESYSTEM_WRITE],
            trust_level=AgentTrustLevel.CORE,
            supported_task_types=["generate_code", "refactor_code"]
        )

    def get_descriptor(self) -> AgentDescriptor:
        return self._descriptor

    def initialize(self, ctx: Dict[str, Any]) -> bool:
        return True

    def execute_task(
        self,
        task_id: str,
        task_type: str,
        payload: Dict[str, Any],
        token: AgentCapabilityToken
    ) -> Dict[str, Any]:
        prompt = payload.get("prompt", "def hello(): pass")
        return {
            "status": "COMPLETED",
            "generated_code": f"# Generated by {self._descriptor.agent_id}\n{prompt}\nprint('Hello Aegis Multi-Agent OS!')",
            "token_valid": token.has_permission(PluginPermission.FILESYSTEM_READ)
        }

    def shutdown(self) -> bool:
        return True


class SecurityAuditorAgent(AgentInterface):
    """Trusted agent responsible for scanning security vulnerabilities."""
    def __init__(self):
        self._descriptor = AgentDescriptor(
            agent_id="agent.trusted.security_auditor",
            name="Aegis Security Auditor Agent",
            version="1.0.0",
            capabilities=["SECURITY_SCAN", "VAULT_CHECK"],
            permissions=[PluginPermission.FILESYSTEM_READ],
            trust_level=AgentTrustLevel.TRUSTED,
            supported_task_types=["security_scan"]
        )

    def get_descriptor(self) -> AgentDescriptor:
        return self._descriptor

    def initialize(self, ctx: Dict[str, Any]) -> bool:
        return True

    def execute_task(
        self,
        task_id: str,
        task_type: str,
        payload: Dict[str, Any],
        token: AgentCapabilityToken
    ) -> Dict[str, Any]:
        target_code = payload.get("code", "")
        has_vulnerabilities = "eval(" in target_code or "exec(" in target_code
        return {
            "status": "COMPLETED",
            "vulnerabilities_found": 1 if has_vulnerabilities else 0,
            "security_score": 100 if not has_vulnerabilities else 40
        }

    def shutdown(self) -> bool:
        return True


def run_agents_demo():
    print("================================================================================")
    print("🛡️ AEGIS AI OS — DISTRIBUTED MULTI-AGENT COORDINATION & EVENT BUS DEMO")
    print("================================================================ algorithm\n")

    # Step 1: Initialize Multi-Agent Subsystem
    print("--- 1. INITIALIZING AGENT REGISTRY & SECURE EVENT BUS ---")
    registry = AgentRegistry()
    event_bus = SecureEventBus()
    coordinator = TaskCoordinator(registry, event_bus, max_delegation_depth=3)

    code_agent = CodeGeneratorAgent()
    sec_agent = SecurityAuditorAgent()

    registry.register_agent(code_agent.get_descriptor(), code_agent)
    registry.register_agent(sec_agent.get_descriptor(), sec_agent)

    print(f"✅ Registered {len(registry.list_agents())} Agents:")
    for desc in registry.list_agents():
        print(f"  • [{desc.trust_level.value}] {desc.agent_id} (v{desc.version}) — Tasks: {', '.join(desc.supported_task_types)}")

    # Step 2: Event Bus Publish & Subscribe
    print("\n--- 2. EVENT BUS PUBLISH & SUBSCRIBE DEMO ---")
    received_events = []

    def telemetry_subscriber(evt: AgentEvent):
        received_events.append(evt)
        print(f"  📡 Telemetry Subscriber Received: '{evt.event_type}' from '{evt.source_agent_id}'")

    event_bus.subscribe("auditor_service", "AGENT_HEALTH_CHECK", telemetry_subscriber)

    health_evt = AgentEvent(
        event_type="AGENT_HEALTH_CHECK",
        source_agent_id="agent.core.code_generator",
        payload={"cpu_usage": "1.2%", "status": "OPTIMAL"}
    )
    event_bus.publish(health_evt)
    print("✅ Event published & delivered via SecureEventBus.")

    # Step 3: Request / Reply Event Pattern
    print("\n--- 3. SYNCHRONOUS REQUEST / REPLY PATTERN DEMO ---")
    def echo_responder(evt: AgentEvent):
        return AgentEvent(
            event_type="AGENT_RESPONSE",
            source_agent_id=evt.target_agent_id,
            target_agent_id=evt.source_agent_id,
            correlation_id=evt.correlation_id,
            payload={"reply_msg": f"Acknowledged request '{evt.payload.get('msg')}'"}
        )

    event_bus.subscribe("agent.trusted.security_auditor", "AGENT_QUERY", echo_responder)

    query_evt = AgentEvent(
        event_type="AGENT_QUERY",
        source_agent_id="agent.core.code_generator",
        target_agent_id="agent.trusted.security_auditor",
        payload={"msg": "Requesting audit status update"}
    )
    t0 = time.time()
    reply = event_bus.request_reply(query_evt, timeout_seconds=2.0)
    rt_latency_ms = (time.time() - t0) * 1000.0

    print(f"📥 Request-Reply Received: {reply.payload['reply_msg']}")
    print(f"⏱️ Round-Trip Request/Reply Latency: {rt_latency_ms:.2f} ms")

    # Step 4: Deterministic Task Coordinator Routing
    print("\n--- 4. DETERMINISTIC TASK COORDINATOR ROUTING ---")
    task_res1 = coordinator.submit_task("generate_code", {"prompt": "def calculate_hash(data): return 42"})
